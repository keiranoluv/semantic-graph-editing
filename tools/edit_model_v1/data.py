"""Train/validation loader and explicit human-review provenance gate. No test labels."""

import csv
import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from src.editing.operations import EditGraph, Operation
from src.knowledge.transe.core import sha256
from tools.edit_model_v1.codec import encode_actions, normalize_label
from tools.prepare_magicbrush import digest
from tools.review_magicbrush import AXES, FIELDS, validate_reviews


@dataclass(frozen=True)
class Example:
    id: str
    split: str
    group: str
    instruction: str
    source: EditGraph
    target: EditGraph
    operations: tuple

    @property
    def simple(self):
        # Predeclared graph-level proxy, not a claim about linguistic simplicity.
        return len(self.operations) == 1

    def model_input(self):
        return {"source": self.source, "instruction": self.instruction}


def read_inputs(manifest_path, edits_path):
    manifest, edits = (json.loads(Path(p).read_text()) for p in (manifest_path, edits_path))
    if edits["dataset_manifest_sha256"] != sha256(manifest_path):
        raise ValueError("Graph labels do not match the dataset manifest")
    index = {r["id"]: r for r in manifest["records"]}
    labels = {r["id"]: r for r in edits["records"]}
    if len(index) != len(manifest["records"]) or len(labels) != len(edits["records"]) or set(labels) - index.keys():
        raise ValueError("Duplicate/unknown pair IDs")
    memberships, groups, pixels = {}, {}, {}
    for split in ("train", "val", "test"):
        for identifier in manifest["splits"][split]:
            if identifier in memberships or identifier not in index:
                raise ValueError("Overlapping or unknown split IDs")
            memberships[identifier] = split
    if memberships.keys() != index.keys():
        raise ValueError("Split membership is incomplete")
    for identifier, row in index.items():
        split = memberships[identifier]
        if row["split"] != split or row["official_split"] != "train":
            raise ValueError("Unexpected split or non-train official provenance")
        for key in (row["source_group_id"], "session:" + row["img_id"]):
            if groups.setdefault(key, split) != split:
                raise ValueError("Source/session leakage across splits")
        for role in ("source_image", "target_image"):
            if pixels.setdefault(row[role]["pixel_sha256"], split) != split:
                raise ValueError("RGB pixel leakage across splits")
        if identifier in labels:
            label = labels[identifier]
            if any(label[k] != row[k] for k in ("split", "source_group_id", "instruction")):
                raise ValueError("Label metadata differs from the original pair")
    return manifest, index, labels


def load_examples(manifest_path, edits_path, *, rejected=(), max_action_tokens=2048):
    manifest, index, labels = read_inputs(manifest_path, edits_path)
    examples = {"train": [], "val": []}
    excluded, support = Counter(), {split: Counter() for split in examples}
    long_validation = []
    problem_counts = Counter()
    for split in examples:
        for identifier in manifest["splits"][split]:
            row, label = index[identifier], labels.get(identifier)
            if identifier in rejected:
                excluded[f"{split}:human_incorrect_or_uncertain"] += 1
                continue
            if (
                not label
                or label.get("status") != "candidate"
                or not label.get("eligible_for_training")
                or label.get("problems")
            ):
                excluded[f"{split}:{label.get('status', 'missing') if label else 'missing'}"] += 1
                for problem in label.get("problems", []) if label else []:
                    problem_counts[f"{split}:{problem}"] += 1
                continue
            source, target = (EditGraph.from_dict(label[k]) for k in ("source_graph", "target_graph"))
            if len(source.nodes) > 20 or len(source.edges) > 60:
                excluded[f"{split}:source_graph_exceeds_model_budget"] += 1
                continue
            operations = tuple(Operation.from_dict(op) for op in label["operations"])
            if not 1 <= len(operations) <= 12:
                raise ValueError("Candidate must contain 1..12 operations")
            try:
                source, target, operations = normalize_label(source, target, operations)
            except ValueError as error:
                if str(error) != "unsupported_ambiguous_new_instance_identity":
                    raise
                excluded[f"{split}:{error}"] += 1
                continue
            token_count = len(encode_actions(operations)) - 1  # Generated bytes + EOS.
            if token_count > max_action_tokens:
                if split == "train":
                    excluded["train:action_sequence_too_long"] += 1
                    continue
                # Keep in denominator; never silently prune hard validation examples.
                long_validation.append(identifier)
            examples[split].append(
                Example(identifier, split, row["source_group_id"], row["instruction"], source, target, operations)
            )
            support[split].update(op.kind for op in operations)
    report = {
        "examples": {k: len(v) for k, v in examples.items()},
        "operation_support": {k: dict(v) for k, v in support.items()},
        "excluded": dict(excluded),
        "excluded_problem_counts": dict(problem_counts),
        "validation_labels_exceeding_decode_budget": long_validation,
        "test_labels_decoded": False,
        "simple_definition": "exactly_one_canonical_GT_operation; graph-level proxy",
        "label_origin": "frozen_image_only_VLM_pseudo_labels_not_GT",
    }
    return examples, report


def review_gate(manifest_path, edits_path, packet_path, csv_path, *, minimum=20, minimum_correct_fraction=0.8):
    manifest, index, labels = read_inputs(manifest_path, edits_path)
    packet = json.loads(Path(packet_path).read_text())
    if packet["packet_sha256"] != digest({k: v for k, v in packet.items() if k != "packet_sha256"}):
        raise ValueError("Review packet was changed")
    if packet["dataset_manifest_sha256"] != sha256(manifest_path):
        raise ValueError("Review belongs to another dataset")
    cases = {r["id"]: r for r in packet["cases"]}
    if len(cases) != len(packet["cases"]) or set(cases) != set(manifest["review_ids"]):
        raise ValueError("Human sample must be the original preselected train cohort")
    with Path(csv_path).open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != list(FIELDS):
            raise ValueError("Unexpected human CSV schema")
        rows = list(reader)
    if len(rows) != len(cases) or {r["pair_id"] for r in rows} != set(cases):
        raise ValueError("Human CSV contains repeated/missing/unknown pair IDs")
    reviews = {}
    for row in rows:
        identifier = row["pair_id"]
        case, original = cases[identifier], index[identifier]
        evidence = digest(
            {
                "source_sha256": original["source_image"]["sha256"],
                "target_sha256": original["target_image"]["sha256"],
                "label": labels.get(identifier),
            }
        )
        expected = {
            "img_id": original["img_id"],
            "turn_index": str(original["turn_index"]),
            "split": "train",
            "source_sha256": original["source_image"]["sha256"],
            "target_sha256": original["target_image"]["sha256"],
            "evidence_sha256": evidence,
            "review_packet_sha256": packet["packet_sha256"],
        }
        if (
            original["split"] != "train"
            or case["evidence_sha256"] != evidence
            or any(row[k] != v for k, v in expected.items())
        ):
            raise ValueError("Human review does not match current per-pair evidence")
        reviews[identifier] = {k: row[k] for k in ("decision", *AXES, "reviewer", "notes")}
    validate_reviews(packet, reviews)
    counts = Counter(r["decision"] or "unreviewed" for r in reviews.values())
    determinate = counts["correct"] + counts["incorrect"]
    fraction = counts["correct"] / determinate if determinate else None
    return {
        "ready": determinate >= minimum and fraction is not None and fraction >= minimum_correct_fraction,
        "decision_counts": dict(counts),
        "determinate_reviews": determinate,
        "correct_fraction_among_determinate": fraction,
        "minimum_reviews": minimum,
        "minimum_correct_fraction": minimum_correct_fraction,
        "rejected_ids": sorted(i for i, r in reviews.items() if r["decision"] in ("incorrect", "uncertain")),
        "review_packet_sha256": packet["packet_sha256"],
        "review_csv_sha256": sha256(csv_path),
        "per_pair_evidence_verified": True,
        "automatically_approved": False,
    }


def feature_texts(source, instruction):
    # Deliberately accepts neither Example nor target/operation metadata.
    return {
        "instruction": instruction,
        "nodes": [json.dumps([n.label, list(n.attributes)], ensure_ascii=False) for n in source.nodes],
        "edges": [e.predicate for e in source.edges],
    }
